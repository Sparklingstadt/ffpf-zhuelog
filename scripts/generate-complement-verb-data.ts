// Turns the complement CSV (中国語の補語_動詞との組み合わせと例文.csv) into
// src/domain/practice/complement-verb-data.ts, the questions of the
// "動詞から選ぶ" mode of complement practice. Usage:
//   pnpm exec tsx scripts/generate-complement-verb-data.ts <csv>
//
// Only rows of 区分 補語 are used. A row becomes one question per verb that
// its 組み合わせ例 shows the complement right after. The hand-written modes
// in complement-data.ts are not touched.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { format, resolveConfig } from "prettier";

import {
  type ComplementVerbUsage,
  wrongComplementsFor,
} from "../src/domain/practice/complement-verb-quiz";
import { CHOICE_COUNT } from "../src/domain/practice/preposition-quiz";

const output = new URL(
  "../src/domain/practice/complement-verb-data.ts",
  import.meta.url,
);

// The categories the wrong-choice rule tells apart; a row in any other fails.
const CATEGORIES = [
  "結果補語",
  "方向補語（単純）",
  "方向補語（複合）",
  "方向補語（派生）",
  "可能補語",
  "程度・様態補語",
] as const;

// RFC 4180: quoted fields may hold commas, quotes ("") and line breaks.
function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") {
      row.push(field);
      field = "";
    } else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      if (row.some((cell) => cell !== "")) rows.push(row);
      row = [];
      field = "";
    } else field += ch;
  }
  row.push(field);
  if (row.some((cell) => cell !== "")) rows.push(row);
  return rows;
}

const list = (cell: string) =>
  cell
    .split("；")
    .map((part) => part.trim())
    .filter(Boolean);

const path = process.argv[2];
if (!path) throw new Error("usage: generate-complement-verb-data.ts <csv>");
const [header, ...records] = parseCsv(
  readFileSync(path, "utf8").replace(/^﻿/, ""),
);
const column = (name: string) => {
  const index = header.indexOf(name);
  if (index === -1) throw new Error(`no column ${name}`);
  return index;
};
const c = {
  id: column("ID"),
  kind: column("区分"),
  category: column("意味分類"),
  complement: column("補語（簡体字）"),
  pinyin: column("ピンイン（見出し）"),
  meaning: column("意味（日本語）"),
  verbs: column("動詞の例（中国語）"),
  phrases: column("組み合わせ例（中国語）"),
  example: column("例文（中国語・オリジナル）"),
  translation: column("例文の和訳"),
};

const usages: ComplementVerbUsage[] = records
  .filter((record) => record[c.kind] === "補語")
  .map((record) => {
    const id = record[c.id];
    const complement = record[c.complement];
    const category = record[c.category];
    if (!(CATEGORIES as readonly string[]).includes(category))
      throw new Error(`${id}: unknown category ${category}`);
    const phrases = list(record[c.phrases]);
    // The phrase of a verb is the first that holds the complement right
    // after it (答对问题 for 答, not 猜对答案).
    const pairs = list(record[c.verbs]).flatMap((verb) => {
      for (const phrase of phrases) {
        const verbAt = phrase.indexOf(verb);
        const at = verbAt + verb.length;
        if (verbAt !== -1 && phrase.startsWith(complement, at))
          return [{ verb, phrase, at }];
      }
      throw new Error(
        `${id}: no phrase shows ${complement} right after ${verb}`,
      );
    });
    return {
      id,
      complement,
      pinyin: record[c.pinyin],
      meaning: record[c.meaning],
      category,
      pairs,
      example: record[c.example],
      translation: record[c.translation],
    };
  });

// Every question must have its three wrong choices; a row that cannot is a
// gap in the CSV (too few complements outside its category).
for (const usage of usages)
  for (const pair of usage.pairs) {
    const wrong = wrongComplementsFor(
      usage.complement,
      pair.verb,
      usages,
    ).length;
    if (wrong < CHOICE_COUNT - 1)
      throw new Error(
        `${usage.id}: only ${wrong} wrong choices for ${pair.verb}`,
      );
  }

// Formatted as the pre-commit hook would, so regenerating the same CSV
// leaves no diff.
const outputPath = fileURLToPath(output);
const source = `// Generated by scripts/generate-complement-verb-data.ts from
// 中国語の補語_動詞との組み合わせと例文.csv. Do not edit by hand.
import type { ComplementVerbUsage } from "./complement-verb-quiz";

export const COMPLEMENT_VERB_USAGES: readonly ComplementVerbUsage[] = ${JSON.stringify(usages, null, 2)};
`;
// No top-level await: tsx runs this package's scripts as CommonJS.
resolveConfig(outputPath)
  .then((config) => format(source, { ...config, filepath: outputPath }))
  .then((formatted) => {
    writeFileSync(outputPath, formatted);
    console.log(
      `${usages.length} usages, ${usages.reduce((sum, usage) => sum + usage.pairs.length, 0)} questions`,
    );
  });
