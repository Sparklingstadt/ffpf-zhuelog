// Turns the preposition CSV (中国語の介詞_名詞との組み合わせと例文.csv) into
// src/domain/practice/preposition-data.ts, the questions of the preposition
// practice. Usage: pnpm exec tsx scripts/generate-preposition-data.ts <csv>
//
// Only rows of a single preposition (区分 介詞・介詞的用法) are used; frames
// such as 在…上 have no one word to pick. A row becomes one question per
// noun that its 組み合わせ例 shows next to the preposition.
import { readFileSync, writeFileSync } from "node:fs";

const output = new URL(
  "../src/domain/practice/preposition-data.ts",
  import.meta.url,
);

// The categories the practice tells apart. 補足の時間・対象・基準表現 rows
// mean the same as rows in these, so each goes where it belongs.
const CATEGORIES = [
  "場所・時間・起点",
  "相手・対象・話題・比較",
  "手段・道具・根拠・基準",
  "原因・条件・除外・資格",
  "処置・受け身・担当者",
] as const;
const MOVED: Record<string, (typeof CATEGORIES)[number]> = {
  P197: "場所・時間・起点", // 直到
  P198: "場所・時間・起点", // 直至
  P199: "相手・対象・話題・比較", // 相对于
  P200: "手段・道具・根拠・基準", // 依着
  P201: "相手・対象・話題・比較", // 于 〜に対して
  P202: "相手・対象・話題・比較", // 于 〜より
};

// RFC 4180: quoted fields may hold commas, quotes ("") and line breaks.
function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") {
      row.push(field);
      field = "";
    } else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      if (row.some((cell) => cell !== "")) rows.push(row);
      row = [];
      field = "";
    } else field += ch;
  }
  row.push(field);
  if (row.some((cell) => cell !== "")) rows.push(row);
  return rows;
}

const list = (cell: string) =>
  cell
    .split("；")
    .map((part) => part.trim())
    .filter(Boolean);

// Where the preposition sits in the phrase, outside the noun.
function prepositionAt(phrase: string, preposition: string, noun: string) {
  const nounAt = phrase.indexOf(noun);
  for (
    let at = phrase.indexOf(preposition);
    at !== -1;
    at = phrase.indexOf(preposition, at + 1)
  ) {
    const end = at + preposition.length;
    if (end <= nounAt || at >= nounAt + noun.length) return at;
  }
  return -1;
}

const path = process.argv[2];
if (!path) throw new Error("usage: generate-preposition-data.ts <csv>");
const [header, ...records] = parseCsv(
  readFileSync(path, "utf8").replace(/^﻿/, ""),
);
const column = (name: string) => {
  const index = header.indexOf(name);
  if (index === -1) throw new Error(`no column ${name}`);
  return index;
};
const c = {
  id: column("ID"),
  kind: column("区分"),
  category: column("意味分類"),
  preposition: column("介詞・表現（簡体字）"),
  pinyin: column("ピンイン（見出し）"),
  meaning: column("意味（日本語）"),
  nouns: column("名詞・句の例（中国語）"),
  phrases: column("組み合わせ例（中国語）"),
  example: column("例文（中国語・オリジナル）"),
  translation: column("例文の和訳"),
};

const usages = records
  .filter((record) => record[c.kind] === "介詞・介詞的用法")
  .map((record) => {
    const id = record[c.id];
    const preposition = record[c.preposition];
    const category = MOVED[id] ?? record[c.category];
    if (!(CATEGORIES as readonly string[]).includes(category))
      throw new Error(`${id}: unknown category ${category}`);
    const phrases = list(record[c.phrases]);
    const pairs = list(record[c.nouns]).flatMap((noun) => {
      for (const phrase of phrases) {
        const at = prepositionAt(phrase, preposition, noun);
        if (phrase.includes(noun) && at !== -1) return [{ noun, phrase, at }];
      }
      return [];
    });
    return {
      id,
      preposition,
      pinyin: record[c.pinyin],
      meaning: record[c.meaning],
      category,
      pairs,
      example: record[c.example],
      translation: record[c.translation],
    };
  })
  .filter((usage) => usage.pairs.length > 0);

writeFileSync(
  output,
  `// Generated by scripts/generate-preposition-data.ts from
// 中国語の介詞_名詞との組み合わせと例文.csv. Do not edit by hand.
import type { PrepositionUsage } from "./preposition-quiz";

export const PREPOSITION_USAGES: readonly PrepositionUsage[] = ${JSON.stringify(usages, null, 2)};
`,
);
console.log(
  `${usages.length} usages, ${usages.reduce((sum, usage) => sum + usage.pairs.length, 0)} questions`,
);
