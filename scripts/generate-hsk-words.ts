// Writes src/domain/practice/hsk-words-official.ts: the HSK 3.0 words of
// level 5 and above that the preposition, complement, measure-word and
// 了・过・着 practices use, and the level of each practice text, from the
// official word list in data/hsk30.csv.
// Usage:
//   node --import tsx scripts/generate-hsk-words.ts
//
// Run it again after changing complement-data.ts, complement-verb-data.ts,
// measure-word-data.ts, aspect-particle-data.ts, preposition-data.ts or
// data/hsk30.csv; tests/hsk-words-official.test.ts fails until then. The segmentation lives in scripts/lib/hsk-words-official.ts.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { format, resolveConfig } from "prettier";

import {
  officialHardWords,
  officialTextLevels,
} from "./lib/hsk-words-official";

const output = new URL(
  "../src/domain/practice/hsk-words-official.ts",
  import.meta.url,
);

const entries = officialHardWords();
const textLevels = officialTextLevels();

// Formatted as the pre-commit hook would, so regenerating leaves no diff.
const outputPath = fileURLToPath(output);
const source = `// Generated by scripts/generate-hsk-words.ts from data/hsk30.csv (HSK 3.0,
// GF0025-2021). Do not edit by hand; run the script again.

// Each word of HSK level 5 or above found in a preposition, complement,
// measure-word or 了・过・着 practice text, with its level; 7 stands for the
// 7–9 band. A word in the list at several levels has the lowest.
export const HSK_OFFICIAL_HARD_WORDS: Readonly<Record<string, 5 | 6 | 7>> = ${JSON.stringify(entries, null, 2)};

// Each practice text whose hardest word, by forward maximum matching against
// the whole list, is of level 5 or above, with that level. Texts of levels
// 1-4 are left out. Looking a text up here, not searching it for the words
// above, keeps 已经 from counting as 经.
export const HSK_OFFICIAL_TEXT_LEVELS: Readonly<Record<string, 5 | 6 | 7>> = ${JSON.stringify(textLevels, null, 2)};
`;
// No top-level await: tsx runs this package's scripts as CommonJS.
resolveConfig(outputPath)
  .then((config) => format(source, { ...config, filepath: outputPath }))
  .then((formatted) => {
    writeFileSync(outputPath, formatted);
    const count = (level: number) =>
      Object.values(entries).filter((value) => value === level).length;
    console.log(
      `${Object.keys(entries).length} words (5: ${count(5)}, 6: ${count(6)}, 7–9: ${count(7)}), ${Object.keys(textLevels).length} texts of level 5 and above`,
    );
  });
